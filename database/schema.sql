                             'report_photo_resolutions', 'report_confirmations',
                             'report_comments', 'report_ratings', 'user_sessions', 'rate_limits']
    LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    END LOOP;
