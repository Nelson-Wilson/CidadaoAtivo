-- ---------------------------------------------------------------------
-- Função partilhada para manter updated_at
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ---------------------------------------------------------------------
-- municipalities
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS municipalities (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(255) NOT NULL,
    region      varchar(255),
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- departments
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS departments (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             varchar(255) NOT NULL,
    municipality_id  integer NOT NULL REFERENCES municipalities(id) ON DELETE CASCADE,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- users (autenticação própria com bcrypt; não usa o Supabase Auth)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             varchar(255) NOT NULL,
    email            varchar(255) NOT NULL UNIQUE,
    password         varchar(255) NOT NULL,
    role             text NOT NULL DEFAULT 'cidadao'
                     CHECK (role IN ('cidadao', 'tecnico', 'municipio', 'admin')),
    municipality_id  integer REFERENCES municipalities(id) ON DELETE SET NULL,
    department_id    integer REFERENCES departments(id) ON DELETE SET NULL,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- user_sessions (sessões revogáveis; substitui cookie-session)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS user_sessions (
    sid         varchar(255) PRIMARY KEY,
    sess        jsonb NOT NULL,
    user_id     integer REFERENCES users(id) ON DELETE CASCADE,
    expire      timestamptz NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_user_sessions_expire ON user_sessions (expire);
CREATE INDEX IF NOT EXISTS idx_user_sessions_user ON user_sessions (user_id);

-- ---------------------------------------------------------------------
-- rate_limits (rate limiting partilhado entre instâncias serverless)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS rate_limits (
    key         varchar(255) PRIMARY KEY,
    total_hits  integer NOT NULL DEFAULT 0,
    reset_time  timestamptz NOT NULL,
    updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_rate_limits_reset ON rate_limits (reset_time);

-- ---------------------------------------------------------------------
-- categories (sla_hours = prazo padrão de resolução, gerido pelo admin)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS categories (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(255) NOT NULL UNIQUE,
    sla_hours   integer NOT NULL DEFAULT 72 CHECK (sla_hours > 0),
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- category_department (pivô)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS category_department (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id    integer NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
    department_id  integer NOT NULL REFERENCES departments(id) ON DELETE CASCADE,
    created_at     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uniq_category_department UNIQUE (category_id, department_id)
);

-- ---------------------------------------------------------------------
-- reports (denúncias)
-- photo_path: URL pública do Supabase Storage (ou caminho relativo em modo local)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS reports (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    category_id      integer NOT NULL REFERENCES categories(id),
    description      text NOT NULL,
    photo_path       varchar(500),
    latitude         numeric(10, 7) NOT NULL,
    longitude        numeric(10, 7) NOT NULL,
    neighborhood     varchar(120),
    status           text NOT NULL DEFAULT 'recebida'
                     CHECK (status IN ('recebida', 'em_analise', 'atribuida', 'em_execucao',
                                       'resolvida', 'fechada', 'rejeitada')),
    priority         text NOT NULL DEFAULT 'normal'
                     CHECK (priority IN ('baixa', 'normal', 'urgente', 'muito_urgente')),
    municipality_id  integer REFERENCES municipalities(id) ON DELETE SET NULL,
    department_id    integer REFERENCES departments(id) ON DELETE SET NULL,
    technician_id    integer REFERENCES users(id) ON DELETE SET NULL,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_reports_status ON reports (status);
CREATE INDEX IF NOT EXISTS idx_reports_category ON reports (category_id);
CREATE INDEX IF NOT EXISTS idx_reports_municipality_department ON reports (municipality_id, department_id);
CREATE INDEX IF NOT EXISTS idx_reports_user_created ON reports (user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_reports_tech_status ON reports (technician_id, status);
CREATE INDEX IF NOT EXISTS idx_reports_coords ON reports (latitude, longitude);
CREATE INDEX IF NOT EXISTS idx_reports_dup_lookup ON reports (category_id, status, latitude, longitude);

-- ---------------------------------------------------------------------
-- report_status_histories (auditoria da máquina de estados)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS report_status_histories (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id        integer NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
    previous_status  varchar(30),
    new_status       varchar(30) NOT NULL,
    changed_by       integer NOT NULL REFERENCES users(id),
    created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_rsh_report ON report_status_histories (report_id, created_at);
-- Nota do município associada à mudança de estado (ex.: "Resposta ao cidadão").
ALTER TABLE report_status_histories ADD COLUMN IF NOT EXISTS note varchar(1000);

-- ---------------------------------------------------------------------
-- report_photo_resolutions (fotos de resolução do técnico)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS report_photo_resolutions (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id      integer NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
    photo_path     varchar(500) NOT NULL,
    technician_id  integer NOT NULL REFERENCES users(id),
    created_at     timestamptz NOT NULL DEFAULT now()
);
-- Observações da intervenção do técnico.
ALTER TABLE report_photo_resolutions ADD COLUMN IF NOT EXISTS note varchar(1000);

-- ---------------------------------------------------------------------
-- report_confirmations = votos "também me afeta" (um por utilizador)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS report_confirmations (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id   integer NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
    user_id     integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uniq_report_user UNIQUE (report_id, user_id)
);

-- ---------------------------------------------------------------------
-- report_comments (comentários públicos; is_official = município/técnico/admin)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS report_comments (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id    integer NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
    user_id      integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    content      varchar(1000) NOT NULL CHECK (length(btrim(content)) > 0),
    is_official  boolean NOT NULL DEFAULT false,
    created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_comments_report ON report_comments (report_id, created_at);

-- ---------------------------------------------------------------------
-- report_ratings (avaliação do cidadão depois da resolução; uma por denúncia)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS report_ratings (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id   integer NOT NULL UNIQUE REFERENCES reports(id) ON DELETE CASCADE,
    user_id     integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    score       integer NOT NULL CHECK (score BETWEEN 1 AND 5),
    feedback    varchar(1000),
    created_at  timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Triggers de updated_at
-- ---------------------------------------------------------------------
DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['municipalities', 'departments', 'users', 'categories', 'reports']
    LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS trg_%1$s_updated_at ON %1$s', t);
        EXECUTE format('CREATE TRIGGER trg_%1$s_updated_at BEFORE UPDATE ON %1$s
                        FOR EACH ROW EXECUTE FUNCTION set_updated_at()', t);
    END LOOP;
END $$;

